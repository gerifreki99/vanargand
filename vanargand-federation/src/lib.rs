//! Free founding of chains, the courier and scout roles, local currencies, and
//! the VAN zone's border with its emission proofs.
//!
//! **Not implemented.**
//!
//! Vanargand is not a blockchain but a family of sovereign networks speaking one
//! language. A chain is identified by the hash of its genesis block, which every
//! signature carries, so cloning a chain is free and harmless: the clone has a
//! running ledger, and no other chain's locks recognise its keys.
//!
//! The border does the policing. VAN presenting at a bridge must trace their
//! genealogy to emissions that match the formula. A conforming chain's VAN are
//! accepted at par; a cheating chain's are demoted to a local currency at
//! whatever rate the market gives them. Nobody votes on exclusion —
//! arithmetic demotes.
//!
//! Tier 3 of the roadmap in `docs/02-scope.pdf`.
