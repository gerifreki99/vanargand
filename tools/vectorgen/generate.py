DOMAINS = [
    "vanargand v1 account id",
    "vanargand v1 device id",
    "vanargand v1 key derivation",
    "vanargand v1 txid",
    "vanargand v1 tx signing",
    "vanargand v1 name commitment",
    "vanargand v1 asset id",
    "vanargand v1 block id",
    "vanargand v1 block signing",
    "vanargand v1 smt leaf",
    "vanargand v1 smt node",
    "vanargand v1 state value",
    "vanargand v1 commitment chain",
    "vanargand v1 payword",
    "vanargand v1 epoch seed",
    "vanargand v1 delay function",
    "vanargand v1 committee draw",
]


def h(context: str, *parts: bytes) -> bytes:
    """BLAKE3 in key-derivation mode: the only way this protocol hashes."""
    hasher = blake3(derive_key_context=context)
    for part in parts:
        hasher.update(part)
    return hasher.digest(length=32)


def chain_root(context: str, seed: bytes, length: int) -> list[bytes]:
    """Links from root (index 0) to seed (index ``length``)."""
    links = [b""] * (length + 1)
    links[length] = seed
    for index in range(length - 1, -1, -1):
        links[index] = h(context, links[index + 1])
    return links


def delay_iterate(value: bytes, count: int) -> bytes:
    """Iterate the sequential delay function.

    Inherently serial: each step needs the previous one. That is the point —
    the last proposer of an epoch must not be able to try several variants of
    the seed within its turn.
    """
    for _ in range(count):
        value = h("vanargand v1 delay function", value)
    return value


def delay_checkpoints(value: bytes, iterations: int, segments: int) -> list[bytes]:
    """The checkpoints of a proof of sequential work: input, boundaries, output."""
    if segments <= 0 or iterations % segments:
        raise ValueError("iterations must be a positive multiple of segments")
    length = iterations // segments
    points = [value]
    for _ in range(segments):
        value = delay_iterate(value, length)
        points.append(value)
    return points


def merkle_list_root(leaves: list[bytes]) -> bytes:
    """Binary Merkle root over a list, promoting an odd last node unchanged.

    The last node is promoted, never duplicated. Duplicating it is
    CVE-2012-2459: two different lists then produce the same root.
    """
    if not leaves:
        return bytes(32)
    level = [h("vanargand v1 smt leaf", leaf) for leaf in leaves]
    while len(level) > 1:
        nxt = []
        for index in range(0, len(level) - 1, 2):
            nxt.append(h("vanargand v1 smt node", level[index], level[index + 1]))
        if len(level) % 2 == 1:
            nxt.append(level[-1])
        level = nxt
    return level[0]


