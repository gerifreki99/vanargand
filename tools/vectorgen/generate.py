def hx(data: bytes) -> str:
    return data.hex()


def build_canonical_encoding() -> dict:
    encode_cases = []
    for value in [0, 1, 2, 127, 128, 129, 255, 256, 300, 16383, 16384,
                  2**32 - 1, 2**32, 2**63, 2**64 - 1]:
        encode_cases.append(
            {"schema": "varint", "value": str(value), "encoding": hx(varint_encode(value))}
        )

    for raw in [b"", b"\x00", b"hello", bytes(range(256))]:
        encode_cases.append(
            {"schema": "bytes", "value": hx(raw), "encoding": hx(encode_bytes(raw))}
        )

    for text in ["", "a", "héllo", "é"]:
        encode_cases.append(
            {
                "schema": "string",
                "value": text,
                "encoding": hx(encode_bytes(text.encode("utf-8"))),
            }
        )

    encode_cases.append(
        {"schema": "bool", "value": "false", "encoding": "00"},
    )
    encode_cases.append(
        {"schema": "bool", "value": "true", "encoding": "01"},
    )
    encode_cases.append(
        {"schema": "option<varint>", "value": "none", "encoding": "00"},
    )
    encode_cases.append(
        {"schema": "option<varint>", "value": "some(0)", "encoding": "0100"},
    )
    encode_cases.append(
        {
            "schema": "seq<varint>",
            "value": "[1, 2, 300]",
            "encoding": hx(encode_seq([varint_encode(1), varint_encode(2), varint_encode(300)])),
        }
    )

    reject_cases = [
        {"schema": "varint", "encoding": "8100", "reason": "not in shortest form"},
        {"schema": "varint", "encoding": "8000", "reason": "not in shortest form"},
        {"schema": "varint", "encoding": "ff8000", "reason": "not in shortest form"},
        {"schema": "varint", "encoding": "80808080808080808000",
         "reason": "ten bytes ending in zero is still not shortest form"},
        {"schema": "varint", "encoding": "80", "reason": "truncated"},
        {"schema": "varint", "encoding": "ffffffffffffffffff02",
         "reason": "overflows u64"},
        {"schema": "varint", "encoding": "ffffffffffffffffffff01",
         "reason": "wider than ten bytes"},
        {"schema": "bool", "encoding": "02", "reason": "bool must be 00 or 01"},
        {"schema": "bool", "encoding": "ff", "reason": "bool must be 00 or 01"},
        {"schema": "option<varint>", "encoding": "02", "reason": "option tag must be 00 or 01"},
        {"schema": "bytes", "encoding": "05616263", "reason": "declared length exceeds input"},
        {"schema": "string", "encoding": "02fffe", "reason": "not valid UTF-8"},
        {"schema": "varint", "encoding": "0100", "reason": "trailing bytes after the object"},
        {"schema": "set<varint>", "encoding": "03030102",
         "reason": "set elements are not in strictly ascending encoded order"},
        {"schema": "set<varint>", "encoding": "020707",
         "reason": "duplicate set element"},
        {"schema": "set<varint>", "encoding": "02ff018002",
         "reason": "255 encodes as ff01 and 256 as 8002, so this is descending in encoded order"},
    ]

    return {
        "_": "Generated by tools/vectorgen/generate.py — do not edit by hand.",
        "spec": "spec/draft/01-canonical-encoding.md",
        "encode": encode_cases,
        "reject": reject_cases,
    }


def build_hashing() -> dict:
    fixed = b"vanargand conformance input"
    registry = [
        {"context": context, "input": hx(fixed), "digest": hx(h(context, fixed))}
        for context in DOMAINS
    ]

    chains = []
    for context in ["vanargand v1 commitment chain", "vanargand v1 payword"]:
        for length in [0, 1, 2, 5, 16]:
            seed = bytes([length]) * 32
            links = chain_root(context, seed, length)
            chains.append(
                {
                    "context": context,
                    "seed": hx(seed),
                    "length": length,
                    "root": hx(links[0]),
                    "reveals": [hx(link) for link in links[1:]],
                }
            )

    merkle = []
    for count in range(0, 6):
        leaves = [bytes([index]) * 32 for index in range(count)]
        merkle.append(
            {
                "leaves": [hx(leaf) for leaf in leaves],
                "root": hx(merkle_list_root(leaves)),
            }
        )

    return {
        "_": "Generated by tools/vectorgen/generate.py — do not edit by hand.",
        "spec": "spec/draft/02-hashing.md",
        "registry": registry,
        "chains": chains,
        "merkle_list": merkle,
    }


def build_addresses() -> dict:
    master = bytes([0x42]) * 32
    paths = [
        ("root", [0]),
        ("device 0", [1, 0]),
        ("device 1", [1, 1]),
        ("scan", [2]),
        ("one-time 7", [3, 7]),
        ("payword 0", [4, 0]),
        ("commitment 0", [5, 0]),
        ("empty", []),
        ("max component", [0xFFFFFFFF]),
    ]
    derivations = [
        {
            "name": name,
            "path": components,
            "path_encoding": hx(encode_path(components)),
            "master_seed": hx(master),
            "derived_seed": hx(derive_seed(master, components)),
        }
        for name, components in paths
    ]

    # Identifiers are computed from *given* public key bytes rather than from a
    # seed, so that they can be checked without an ML-DSA implementation.
    identifiers = []
    for algorithm, length, label in [(0x01, 1312, "ML-DSA-44"), (0x10, 32, "INSECURE-TEST")]:
        for filler in [0x00, 0xFF, 0xA5]:
            public_key = bytes([filler]) * length
            account = account_id(algorithm, public_key)
            identifiers.append(
                {
                    "algorithm": algorithm,
                    "algorithm_name": label,
                    "public_key": hx(public_key),
                    "account_id": hx(account),
                    "device_id": hx(device_id(algorithm, public_key)),
                    "address_mainnet": address_text("van", 0, account),
                    "address_testnet": address_text("tvan", 0, account),
                }
            )

    addresses = [
        {
            "payload": hx(payload),
            "version": 0,
            "mainnet": address_text("van", 0, payload),
            "testnet": address_text("tvan", 0, payload),
        }
        for payload in [bytes(32), bytes([0xFF]) * 32, bytes(range(32))]
    ]

    rejects = [
        {"address": "van1qqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqq",
         "reason": "bad checksum"},
        {"address": "Van1" + address_text("van", 0, bytes(32))[4:],
         "reason": "mixed case"},
        {"address": address_text("van", 0, bytes(32))[:-1],
         "reason": "truncated, checksum fails"},
        {"address": address_text("tvan", 0, bytes(32)),
         "reason": "test network address, rejected on mainnet"},
        {"address": "A1G7SGD8", "reason": "Bech32 rather than Bech32m"},
        {"address": "van1qqqqq", "reason": "payload is not 32 bytes"},
    ]

    return {
        "_": "Generated by tools/vectorgen/generate.py — do not edit by hand.",
        "spec": "spec/draft/03-addresses.md",
        "derivations": derivations,
        "identifiers": identifiers,
        "addresses": addresses,
        "reject": rejects,
    }


BUILDERS = {
    "01-canonical-encoding.json": build_canonical_encoding,
    "02-hashing.json": build_hashing,
    "03-addresses.json": build_addresses,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed vectors match what this script generates",
    )
    args = parser.parse_args()

    self_check()

    VECTORS.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, builder in BUILDERS.items():
        path = VECTORS / name
        text = json.dumps(builder(), indent=2, ensure_ascii=False) + "\n"
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")

    if args.check:
        if stale:
            print("stale vectors: " + ", ".join(stale), file=sys.stderr)
            print("run: python tools/vectorgen/generate.py", file=sys.stderr)
            return 1
        print("vectors are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
