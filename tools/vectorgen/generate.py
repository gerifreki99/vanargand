"""Generate the conformance test vectors in ``spec/vectors/``.

This is a **second, independent implementation** of the frozen parts of the
specification, written from the prose in ``spec/draft/`` and deliberately not
from the Rust source. That is the whole point of it: vectors generated by the
implementation they are meant to test prove nothing at all, whereas two
implementations written from the same document and agreeing is evidence that
the document says what its author thought it said.

Where the two disagree, the disagreement is the finding. Neither side wins
automatically — the bug is as likely to be in the prose as in either program.

Written in the plainest Python available, with no dependency but ``blake3``, so
that a reader can check it against the specification by eye.

Usage::

    pip install blake3
    python tools/vectorgen/generate.py            # write the vectors
    python tools/vectorgen/generate.py --check    # verify they are up to date
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

from blake3 import blake3

REPO = pathlib.Path(__file__).resolve().parents[2]
VECTORS = REPO / "spec" / "vectors"


# --------------------------------------------------------------------------
# 01 — canonical encoding
# --------------------------------------------------------------------------

MAX_VARINT_BYTES = 10


def varint_encode(value: int) -> bytes:
    """Unsigned LEB128, shortest form."""
    if value < 0 or value > 0xFFFFFFFFFFFFFFFF:
        raise ValueError("varint is u64")
    out = bytearray()
    while value >= 0x80:
        out.append((value & 0x7F) | 0x80)
        value >>= 7
    out.append(value & 0x7F)
    return bytes(out)


def varint_decode(data: bytes) -> tuple[int, int]:
    """Return ``(value, bytes_consumed)``, raising on any non-canonical input."""
    value = 0
    shift = 0
    for index, byte in enumerate(data):
        if index >= MAX_VARINT_BYTES:
            raise ValueError("varint wider than ten bytes")
        payload = byte & 0x7F
        if payload << shift > 0xFFFFFFFFFFFFFFFF:
            raise ValueError("varint overflows u64")
        value |= payload << shift
        if byte & 0x80 == 0:
            if index > 0 and byte == 0:
                raise ValueError("varint is not in shortest form")
            return value, index + 1
        shift += 7
    raise ValueError("varint truncated")


def encode_bytes(data: bytes) -> bytes:
    return varint_encode(len(data)) + data


def encode_seq(items: list[bytes]) -> bytes:
    return varint_encode(len(items)) + b"".join(items)


