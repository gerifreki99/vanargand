# 03 — addresses
# --------------------------------------------------------------------------

CHARSET = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"
BECH32M_CONST = 0x2BC830A3


def bech32_polymod(values: list[int]) -> int:
    generator = [0x3B6A57B2, 0x26508E6D, 0x1EA119FA, 0x3D4233DD, 0x2A1462B3]
    checksum = 1
    for value in values:
        top = checksum >> 25
        checksum = ((checksum & 0x1FFFFFF) << 5) ^ value
        for index in range(5):
            checksum ^= generator[index] if ((top >> index) & 1) else 0
    return checksum


def bech32_hrp_expand(hrp: str) -> list[int]:
    return [ord(c) >> 5 for c in hrp] + [0] + [ord(c) & 31 for c in hrp]


def bech32m_encode(hrp: str, data: list[int]) -> str:
    values = bech32_hrp_expand(hrp) + data
    polymod = bech32_polymod(values + [0, 0, 0, 0, 0, 0]) ^ BECH32M_CONST
    checksum = [(polymod >> 5 * (5 - i)) & 31 for i in range(6)]
    return hrp + "1" + "".join(CHARSET[d] for d in data + checksum)


def bech32m_decode(text: str) -> tuple[str, list[int]]:
    if len(text) > 90:
        raise ValueError("too long")
    if text.lower() != text and text.upper() != text:
        raise ValueError("mixed case")
    text = text.lower()
    position = text.rfind("1")
    if position < 1 or position + 7 > len(text):
        raise ValueError("bad separator position")
    hrp, data_part = text[:position], text[position + 1 :]
    if any(not (33 <= ord(c) <= 126) for c in hrp):
        raise ValueError("bad hrp character")
    if any(c not in CHARSET for c in data_part):
        raise ValueError("bad data character")
    data = [CHARSET.index(c) for c in data_part]
    if bech32_polymod(bech32_hrp_expand(hrp) + data) != BECH32M_CONST:
        raise ValueError("bad checksum")
    return hrp, data[:-6]


def convert_bits(data: list[int], frm: int, to: int, pad: bool) -> list[int]:
    accumulator = 0
    bits = 0
    out = []
    maximum = (1 << to) - 1
    for value in data:
        if value < 0 or (value >> frm):
            raise ValueError("value out of range")
        accumulator = (accumulator << frm) | value
        bits += frm
        while bits >= to:
            bits -= to
            out.append((accumulator >> bits) & maximum)
    if pad:
        if bits:
            out.append((accumulator << (to - bits)) & maximum)
    elif bits >= frm or ((accumulator << (to - bits)) & maximum):
        raise ValueError("non-canonical padding")
    return out


def address_text(hrp: str, version: int, payload: bytes) -> str:
    return bech32m_encode(hrp, [version] + convert_bits(list(payload), 8, 5, True))


def account_id(algorithm: int, public_key: bytes) -> bytes:
    return h("vanargand v1 account id", bytes([algorithm]), public_key)


def device_id(algorithm: int, public_key: bytes) -> bytes:
    return h("vanargand v1 device id", bytes([algorithm]), public_key)


def encode_path(components: list[int]) -> bytes:
    if len(components) > 8:
        raise ValueError("path too long")
    return bytes([len(components)]) + b"".join(
        c.to_bytes(4, "little") for c in components
    )


def derive_seed(master: bytes, components: list[int]) -> bytes:
    return h("vanargand v1 key derivation", encode_path(components), master)


# --------------------------------------------------------------------------
# Self-check: BIP-350 reference vectors
# --------------------------------------------------------------------------

# The reference vectors from BIP-350. The two long ones are written as
# expressions rather than as literals because transcribing an 83-character run
# of the same letter by hand is how a reference vector silently stops being one
# — which is exactly what happened on the first attempt here, and what this
# self-check caught.
BIP350_VALID = [
    "A1LQFN3A",
    "a1lqfn3a",
    "an83characterlonghumanreadablepartthatcontainsthet"
    "heexcludedcharactersbioandnumber11sg7hg6",
    "abcdef1l7aum6echk45nj3s0wdvt2fg8x9yrzpqzd3ryx",
    "11" + "l" * 83 + "udsr8",
    "split1checkupstagehandshakeupstreamerranterredcaperredlc445v",
    "?1v759aa",
]

BIP350_INVALID = [
    "qyrz8wqd2c9m",
    "1qyrz8wqd2c9m",
    "y1b0jsk6g",
    "lt1igcx5c0",
    "in1muywd",
    "mm1crxm3i",
    "au1s5cgom",
    "M1VUXWEZ",
    "16plkw9",
    "1p2gdwpf",
    "A1G7SGD8",  # valid Bech32, not Bech32m
]


def self_check() -> None:
    for text in BIP350_VALID:
        bech32m_decode(text)
    for text in BIP350_INVALID:
        try:
            bech32m_decode(text)
        except ValueError:
            continue
        raise AssertionError(f"BIP-350 invalid vector was accepted: {text}")

    for value in [0, 1, 127, 128, 300, 2**32 - 1, 2**64 - 1]:
        assert varint_decode(varint_encode(value)) == (value, len(varint_encode(value)))
    for bad in [b"\x81\x00", b"\x80\x00", b"\xff\x80\x00"]:
        try:
            varint_decode(bad)
        except ValueError:
            continue
        raise AssertionError(f"non-canonical varint accepted: {bad!r}")

    assert len(set(DOMAINS)) == len(DOMAINS), "duplicate domain context"


